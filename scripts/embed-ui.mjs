import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {build} from 'esbuild';
import {packModelAsset} from './pack-model-asset.mjs';
const root=path.resolve(import.meta.dirname,'..');
const hosted=process.argv.includes('--hosted');
const hostedRoot=path.join(root,'.local/hosted');
const output=hosted?path.join(hostedRoot,'entry.js'):path.join(root,'worker/index.js');
if(hosted){
  fs.rmSync(hostedRoot,{recursive:true,force:true});
  fs.mkdirSync(path.join(hostedRoot,'public/guardian-media'),{recursive:true});
}
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const pageFiles={'/wolfgang-3d':'wolfgang-3d.html','/':'landing.html','/demo':'demo.html','/tour':'tour.html','/login':'access.html','/signup':'access.html','/workspace':'workspace.html','/inspector':'inspector.html','/welcome':'welcome.html','/connections':'connections.html','/account':'account.html','/privacy':'privacy.html','/data-deletion':'data-deletion.html','/plans':'plans.html'};
const pages=Object.fromEntries(Object.entries(pageFiles).map(([url,file])=>[url,read('web/'+file)]));
const types={'.glb':'model/gltf-binary','.svg':'image/svg+xml','.png':'image/png','.webp':'image/webp','.jpg':'image/jpeg','.ico':'image/x-icon','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8'};
const aliases=new Set(['favicon.svg','guardian-logo.svg','favicon-32.png','apple-touch-icon.png','favicon.ico','people-organised-logo.png']);
const publicAssets={};
for(const filename of fs.readdirSync(path.join(root,'web/assets'))){
  const type=['evidence-english.gz','evidence-ocr.wasm.gz'].includes(filename)?'application/gzip':filename==='evidence-notices.txt'?'text/plain; charset=utf-8':types[path.extname(filename)];
  if(!type||filename.startsWith('uk-')||['organisation-directory.js','public-research-sources.js','wolfgang.png','wolfgang-portrait.png','message-first-look.js','url-signals.js','quick-text-check.js'].includes(filename))continue;
  const raw=fs.readFileSync(path.join(root,'web/assets',filename));
  let asset;
  if(filename==='wolfgang.glb'&&hosted){
    const digest=createHash('sha256').update(raw).digest('hex');
    const mediaPath='/guardian-media/'+digest+'.glb';
    fs.writeFileSync(path.join(hostedRoot,'public',mediaPath),raw);
    asset={type,size:raw.length,etag:'"'+digest+'"',mediaPath};
  }else if(filename==='wolfgang.glb')asset=packModelAsset(raw,type);
  else if(type.includes('charset=utf-8')||type==='image/svg+xml'){
    asset=raw.length>=32768?{type,gzip:gzipSync(raw,{level:9}).toString('base64')}:{type,text:raw.toString('utf8')};
  }else asset={type,data:raw.toString('base64')};
  publicAssets['/assets/'+filename]=asset;
  if(aliases.has(filename))publicAssets['/'+filename]=asset;
}
const bundle=await build({metafile:true,stdin:{contents:"export {default} from './server.js'; export {analyse,runCheck,validateResult} from './legacy-analysis.js';",resolveDir:path.join(root,'worker'),sourcefile:'entry.js'},bundle:true,format:'esm',target:'es2022',platform:'browser',outfile:output,banner:{js:'// Generated by scripts/embed-ui.mjs. Edit source modules.\nconst pages='+JSON.stringify(pages)+';\nconst publicAssets='+JSON.stringify(publicAssets)+';'},minify:false});
// A successful ESM import alone misses unresolved optional dynamic imports.
for(const file of Object.values(bundle.metafile.outputs)){
  const external=file.imports.find(entry=>entry.external);
  if(external)throw new Error('Unbundled Worker dependency: '+external.path);
}
// Identify the actual bundle a hostname is serving, even if a rollout fails
// after updating the Worker. The fingerprint contains no runtime settings.
const fingerprint=createHash('sha256').update(fs.readFileSync(output)).digest('hex').slice(0,20);
fs.appendFileSync(output,'\nconst guardianBuildId='+JSON.stringify(fingerprint)+';\n');
const marker='<meta name="guardian-build" content="'+fingerprint+'"></head>';
fs.appendFileSync(output,'pages["/"]=pages["/"].replace("</head>",'+JSON.stringify(marker)+');\n');
console.log('Embedded '+Object.keys(pages).length+' pages and '+Object.keys(publicAssets).length+' asset routes.');
